function makeSignalSeries(baseLikes: number, baseBookmarks: number): DailySignalPoint[] {
  const days = 14;
  const out: DailySignalPoint[] = [];
  for (let i = days - 1; i >= 0; i -= 1) {
    const d = new Date(Date.UTC(2026, 10, 20 - i));
    const factor = (days - i) / days;
    out.push({
      date: d.toISOString().slice(0, 10),
      githubStarsDelta: 0,
      internalLikes: Math.round(baseLikes * (0.3 + 0.7 * factor)),
      internalBookmarks: Math.round(baseBookmarks * (0.25 + 0.75 * factor)),
    });
  }
  return out;
}

